(async () => {
  const checks = [];
  const check = (name, condition) => { if (!condition) throw new Error(name); checks.push(name); };
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  const text = () => document.querySelector('#soundDescription').textContent;
  document.querySelector('[data-tab="mic"]').click();
  check('renamed tab and heading', document.querySelector('#mic h2').textContent === '聲音譜圖');
  check('waiting message', text().includes('開啟麥克風'));
  const context = new AudioContext();
  await context.resume();
  const destination = context.createMediaStreamDestination();
  const gain = context.createGain();
  gain.gain.value = 0.005;
  gain.connect(destination);
  const oscillator = context.createOscillator();
  oscillator.frequency.value = 150;
  oscillator.connect(gain);
  oscillator.start();
  navigator.mediaDevices.getUserMedia = async () => destination.stream;
  document.querySelector('#startMic').click();
  await wait(2500);
  check('low tone', /低沉.*單純/.test(text()));
  const lowText = text();
  const freeze = document.querySelector('#freezeMic');
  freeze.click();
  oscillator.frequency.value = 4000;
  await wait(1000);
  check('freeze keeps description', text() === lowText && document.querySelector('#soundDescriptionStatus').textContent.includes('已凍結'));
  freeze.click();
  await wait(2500);
  check('unfreeze follows high tone', /明亮.*單純/.test(text()));
  oscillator.type = 'sawtooth';
  oscillator.frequency.value = 440;
  await wait(2500);
  check('harmonics produce richer texture', text().includes('成分較豐富'));
  oscillator.disconnect();
  const noiseBuffer = context.createBuffer(1, context.sampleRate, context.sampleRate);
  const noiseSamples = noiseBuffer.getChannelData(0);
  for (let i = 0; i < noiseSamples.length; i++) noiseSamples[i] = Math.random() * 2 - 1;
  const noise = context.createBufferSource();
  noise.buffer = noiseBuffer;
  noise.loop = true;
  noise.connect(gain);
  noise.start();
  await wait(2500);
  check('broadband noise sounds noisy', text().includes('沙沙或嘶嘶'));
  noise.stop();
  noise.disconnect();
  oscillator.connect(gain);
  gain.gain.value = 0;
  await wait(2000);
  check('silence has no stale colour', text().includes('太微弱') && document.querySelector('#soundDescriptionEvidence').textContent === '');
  gain.gain.value = 0.005;
  oscillator.type = 'sine';
  await wait(2000);
  check('sound recovers after silence', text().includes('單純'));
  check('input status recovers after silence', !document.querySelector('#micStatus').textContent.includes('收到靜音'));
  document.querySelector('#stopMic').click();
  check('stop clears description and metrics', text().includes('收音已停止') && document.querySelector('#dbValue').textContent === '-- dB');
  const nextDestination = context.createMediaStreamDestination();
  gain.connect(nextDestination);
  navigator.mediaDevices.getUserMedia = async () => nextDestination.stream;
  document.querySelector('#startMic').click();
  await wait(2000);
  check('restart receives fresh signal', text().includes('單純'));
  document.querySelector('#stopMic').click();
  navigator.mediaDevices.getUserMedia = async () => { throw new DOMException('Test permission denied', 'NotAllowedError'); };
  document.querySelector('#startMic').click();
  await wait(250);
  check('permission error explained', document.querySelector('#soundDescriptionStatus').textContent === '無法收音');
  const finalDestination = context.createMediaStreamDestination();
  gain.connect(finalDestination);
  navigator.mediaDevices.getUserMedia = async () => finalDestination.stream;
  document.querySelector('#startMic').click();
  await wait(2000);
  window.soundLabTestAudio = { context, gain, oscillator };
  return { checks, description: text(), evidence: document.querySelector('#soundDescriptionEvidence').textContent };
})()
